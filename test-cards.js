const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8').replace(/\r\n/g, '\n');
const start = html.indexOf('    function renderCardHTML(');
const end = html.indexOf('    function runCardAnimationLifecyclePass()', start);
assert(start >= 0 && end > start);
const context = { resolveCardAnimationStyle: () => ({}), SUIT_SVG: { S: '<svg></svg>', H: '<svg></svg>' }, SUIT_SVG_MINI: { S: '<svg></svg>', H: '<svg></svg>' }, ROYAL_FACE_ART: {} };
vm.createContext(context);
vm.runInContext(html.slice(start, end), context);
const card = { uid: 'card-1', rank: 'A', suit: 'H' };
const selectable = context.renderCardHTML(card, { selectable: true, selected: true });
assert.match(selectable, /aria-label="Ace of hearts"/);
assert.match(selectable, /role="button"/);
assert.match(selectable, /tabindex="0"/);
assert.match(selectable, /aria-pressed="true"/);
const normal = context.renderCardHTML(card);
assert.match(normal, /role="img" aria-label="Ace of hearts"/);
assert.doesNotMatch(normal, /tabindex=/);
const hidden = context.renderCardHTML(card, { faceDown: true });
assert.match(hidden, /aria-label="Face-down card"/);
assert.doesNotMatch(hidden, /Ace of hearts/);
console.log('Card labels, selection accessibility and hidden-card checks passed');
